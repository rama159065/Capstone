"""Pin Colab to the package versions tested on the PC (``uv.lock``) without touching Colab's own runtime.

    python -m scripts.common.colab_constraints          # writes deploy/colab_constraints.txt from uv.lock
    python -m scripts.common.colab_constraints --check  # exit 1 when the file is out of date with uv.lock/pyproject

The Colab notebooks install with ``pip install -c deploy/colab_constraints.txt ...``. A constraint only fixes the
version of a package that something installs; it adds nothing by itself.

What is pinned: the project's own stack, i.e. every direct dependency in ``pyproject.toml`` and the transitive packages
whose version changes behaviour (LangGraph's checkpoint/prebuilt/sdk, pydantic, starlette, tokenizers,
huggingface-hub, safetensors, openai, tiktoken). ``chromadb`` is pinned in pyproject as well (``==1.5.9``): the index
written on Colab and the server that reads it must use the same version.

What is left to Colab: torch, torchvision and the CUDA/NVIDIA/triton wheels (Colab's GPU build must stay), Jupyter and
the kernel's packages (tornado, ipykernel, ...), and the scientific base (numpy, pandas, scikit-learn, matplotlib,
pillow, protobuf, requests, httpx), which Colab preinstalls and the kernel has already imported. Changing those
mid-session needs a runtime restart and can break Colab's own tools. Our version ranges accept Colab's versions.
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

from scripts.common.paths import ROOT

LOCK = ROOT / "uv.lock"
PYPROJECT = ROOT / "pyproject.toml"
OUTPUT = ROOT / "deploy" / "colab_constraints.txt"

LEFT_TO_COLAB = {"torch", "torchvision", "jupyterlab", "pytest", "matplotlib", "pandas", "scikit-learn", "nltk", "tqdm"}
TRANSITIVE = ("langgraph-checkpoint", "langgraph-prebuilt", "langgraph-sdk", "pydantic", "pydantic-core", "starlette",
              "tokenizers", "huggingface-hub", "safetensors", "openai", "tiktoken")


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def direct_dependencies() -> list[str]:
    deps = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))["project"]["dependencies"]
    return [normalize(re.split(r"[<>=!~ \[;]", dep, maxsplit=1)[0]) for dep in deps]


def locked_versions() -> dict[str, str]:
    versions: dict[str, list[str]] = {}
    for package in tomllib.loads(LOCK.read_text(encoding="utf-8"))["package"]:
        versions.setdefault(normalize(package["name"]), []).append(package["version"])
    multiple = {name: found for name, found in versions.items() if len(found) > 1}
    if multiple:
        raise ValueError(f"uv.lock holds several versions of {multiple}: pin them by hand")
    return {name: found[0] for name, found in versions.items()}


def render() -> str:
    locked = locked_versions()
    names = [name for name in direct_dependencies() if name not in LEFT_TO_COLAB] + list(TRANSITIVE)
    missing = [name for name in names if name not in locked]
    if missing:
        raise ValueError(f"not in uv.lock: {missing} (run uv lock)")
    python = tomllib.loads(LOCK.read_text(encoding="utf-8")).get("requires-python", "")
    lines = ["# Generated by python -m scripts.common.colab_constraints from uv.lock: do not edit by hand.",
             f"# Colab installs with pip install -c deploy/colab_constraints.txt ...  (Python {python}).",
             "# torch/torchvision/CUDA, Jupyter and Colab's numpy/pandas/scikit-learn stay as Colab ships them."]
    lines += [f"{name}=={locked[name]}" for name in sorted(dict.fromkeys(names))]
    return "\n".join(lines) + "\n"


def pinned() -> dict[str, str]:
    """The constraints file as {package: version}."""
    rows = {}
    for line in OUTPUT.read_text(encoding="utf-8").splitlines():
        if line and not line.startswith("#"):
            name, version = line.split("==")
            rows[name] = version
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file differs from what uv.lock gives")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date: run python -m scripts.common.colab_constraints")
            return 1
        print(f"{OUTPUT} matches uv.lock ({len(pinned())} packages)")
        return 0
    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({text.count('==')} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
